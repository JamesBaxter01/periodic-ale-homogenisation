"""LaTeX for the paper's figures and tables, written next to the files the scripts produce.

Each paper script writes one .tex file per float (figure or table environment with its caption and
label), ready to paste into the manuscript or \\input. Captions are templates in the scripts'
settings: <<name>> is replaced by a value taken from the data the figure was made from, so the
caption always states the settings of the run that is plotted.
"""

import re
from pathlib import Path

FIGURE_FOLDER = "Figures"  # where the manuscript keeps the figure files (\includegraphics path)


def number(value, digits=3):
    """A number for LaTeX math: 0.2, 20, 1.5 or 1.2\\times10^{-3}."""
    value = float(value)
    if value == 0 or 1e-3 <= abs(value) < 1e4:
        rounded = float(f"{value:.{digits}g}")  # 'g' alone writes 2000 as 2e+03
        return f"{rounded:.0f}" if rounded.is_integer() else f"{rounded:g}"
    mantissa, exponent = f"{value:.{digits - 1}e}".split("e")
    mantissa = mantissa.rstrip("0").rstrip(".")
    power = rf"10^{{{int(exponent)}}}"
    return power if mantissa == "1" else rf"{mantissa}\times{power}"


def quantity(value, unit="", digits=3):
    """$value\\,\\mathrm{unit}$."""
    suffix = rf"\,\mathrm{{{unit}}}" if unit else ""
    return f"${number(value, digits)}{suffix}$"


def listing(values, unit="", digits=3):
    """$1$, $10$, $20$ and $30\\,\\mathrm{Pa}$: the unit on the last value only."""
    items = [f"${number(v, digits)}$" for v in values[:-1]] + [quantity(values[-1], unit, digits)]
    return items[0] if len(items) == 1 else ", ".join(items[:-1]) + " and " + items[-1]


def words(n):
    """Whole numbers up to twelve in words (as in running text), larger ones as digits."""
    names = "zero one two three four five six seven eight nine ten eleven twelve".split()
    return names[n] if 0 <= n < len(names) else str(n)


def percent(fraction, digits=3):
    return rf"${number(100 * fraction, digits)}\%$"


def fill(template, **values):
    """Replace every <<name>> in template; a name without a value is an error."""
    missing = sorted(set(re.findall(r"<<(\w+)>>", template)) - set(values))
    if missing:
        raise KeyError(f"caption placeholders without a value: {missing}")
    return re.sub(r"<<(\w+)>>", lambda m: str(values[m.group(1)]), template)


def figure(label, caption, panels, placement="tb", width=0.48, single_width=0.6, per_row=2):
    """A figure environment. panels: [(file stem, subcaption, sublabel)]; one panel is drawn without
    a subfigure. per_row subfigures per row. width: one fraction of the text width for every subfigure,
    or one per panel (e.g. to give panels of different aspect ratios the same height)."""
    widths = width if isinstance(width, (list, tuple)) else [width] * len(panels)
    lines = [rf"\begin{{figure}}[pos={placement}]", r"    \centering"]
    if len(panels) == 1:
        lines.append(rf"    \includegraphics[width={single_width}\linewidth]{{{FIGURE_FOLDER}/{panels[0][0]}.pdf}}")
    for i, ((stem, subcaption, sublabel), width) in enumerate(zip(panels, widths) if len(panels) > 1 else []):
        if i:
            lines.append(r"    \hfill" if i % per_row else r"    \medskip")
        lines += [rf"    \begin{{subfigure}}[t]{{{width}\textwidth}}", r"        \centering",
                  rf"        \includegraphics[width=\linewidth]{{{FIGURE_FOLDER}/{stem}.pdf}}",
                  rf"        \caption{{{subcaption}}}", rf"        \label{{{sublabel}}}", r"    \end{subfigure}"]
    lines += [rf"    \caption{{{caption}}}", rf"    \label{{{label}}}", r"\end{figure}"]
    return "\n".join(lines) + "\n"


def relative(path, root):
    """path relative to root where it lies inside it, for the generated files' headers."""
    path = Path(path).resolve()
    return str(path.relative_to(root)) if path.is_relative_to(root) else str(path)


def write(path, text, source):
    """Save text with a header naming the script and data it came from; prints the path."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(f"% Generated by {source}; rerun it rather than editing here.\n{text}")
    print(f"  {path}")
    return path
